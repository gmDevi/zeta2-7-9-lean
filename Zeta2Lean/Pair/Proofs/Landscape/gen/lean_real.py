"""Generate ../RealProfile.lean: certificate for (L-ii)  Phi(xi, 0) <= -18/25 on [1/40, 7/100].

Preal(xi) = sum_j s_j xlx(xi + A_j),  xlx(u) = u log|u|.  On a cell [l, r] every summand is monotone
(argument in [2/5, oo): xlx increasing; in [0, 1/3] or [-1/3, 0]: decreasing), so
s_j xlx(xi + A_j) <= s_j xlx(e_j + A_j) with e_j in {l, r}; the endpoint values are bounded with the
rational log certificates of landscape_common.py.  Exact Fraction arithmetic throughout.

usage: python lean_real.py          (writes ../RealProfile.lean)
       python lean_real.py search   (re-runs the greedy cell search on the 1/2000 grid)
"""
import os
import sys
from fractions import Fraction as Fr
from landscape_common import log_upper, log_lower

hE = [-17, 1, 2, 3, 5, 6]
TERMS = [(1, Fr(40 + h, 40)) for h in hE] + [(-1, Fr(-h, 40)) for h in hE] + [(-6, Fr(1)), (6, Fr(0))]
# order of the summands as in Preal: (+1: xi+1+eta_p, -1: xi-eta_p) pairs, then -6 xlx(xi+1), +6 xlx(xi)
ORDER = [0, 6, 1, 7, 2, 8, 3, 9, 4, 10, 5, 11, 12, 13]
D = 2000
CELLS = [(50, 58), (58, 68), (68, 80), (80, 93), (93, 100), (100, 112), (112, 124), (124, 136), (136, 140)]
TARGET = Fr(-18, 25)


def kind(lo, hi):
    if lo >= Fr(2, 5): return 'inc'
    if lo >= 0 and hi <= Fr(1, 3): return 'decp'
    if lo >= Fr(-1, 3) and hi <= 0: return 'decn'
    raise ValueError("argument range %s..%s not covered by a monotonicity lemma" % (lo, hi))


def side(s, k):
    return 'r' if ((s > 0) == (k == 'inc')) else 'l'


def xlx_bound(v, dirn):
    """certified bound c: dirn 'up': xlx v <= c ; 'lo': c <= xlx v.  Returns (c, info)."""
    if v == 0: return Fr(0), None
    if v > 0:
        if dirn == 'up':
            U, t = log_upper(v); return v*U, t
        L, t = log_lower(v); return v*L, t
    w = -v   # xlx(-w) = -w log w
    if dirn == 'up':
        L, t = log_lower(w); return -w*L, t
    U, t = log_upper(w); return -w*U, t


def cell_bound(l, r):
    L = Fr(l, D); R = Fr(r, D); tot = Fr(0)
    for s, A in TERMS:
        k = kind(L + A, R + A)
        e = R if side(s, k) == 'r' else L
        c, _ = xlx_bound(e + A, 'up' if s > 0 else 'lo')
        tot += s*c
    return tot


def search(slack=Fr(1, 1000), forced=(100,)):
    cells = []; k = 50
    while k < 140:
        limit = min([f for f in forced if f > k] + [140]); best = None
        for k2 in range(k + 1, limit + 1):
            if cell_bound(k, k2) <= TARGET - slack: best = k2
            else: break
        if best is None: raise RuntimeError("no cell from %d" % k)
        cells.append((k, best)); k = best
    return cells


def num(v):
    v = Fr(v)
    if v == 0: return "0"
    if v < 0: return "-(%s)" % num(-v)
    if v.denominator == 1: return "%d" % v.numerator
    return "%d / %d" % (v.numerator, v.denominator)


def rnum(v): return "(%s : ℝ)" % num(v)


def arg_expr(A):
    if A == 0: return "ξ"
    if A == 1: return "ξ + 1"
    if A > 0: return "ξ + %d / %d" % (A.numerator, A.denominator)
    return "ξ - %d / %d" % ((-A).numerator, (-A).denominator)


HEADER = '''import Zeta2Lean.Pair.Proofs.Landscape.Numerics

/-!
# (L-ii) The real profile of configuration E: `Φ(ξ, 0) ≤ -18/25` on `[1/40, 7/100]`

`Preal ξ = ∑_j s_j (ξ + A_j) log|ξ + A_j|` is `PhiE ξ 0` (`Growth.lean`, `PhiE_zero_eq_Preal`;
the linear terms cancel because `∑ η_p = 0`).

**Certificate** (generated by `Landscape/gen/lean_real.py`, exact rational arithmetic):
`[1/40, 7/100]` is cut into nine cells with endpoints in `(1/2000) ℤ` (a breakpoint at `1/20`,
where `ξ - 1/20` changes sign).  On each cell every summand `s_j x log x` (at `x = ξ + A_j`) is
monotone (`xlx_mono`, `xlx_anti_pos`, `xlx_anti_neg`: all fourteen arguments stay in `[2/5, ∞)`,
`[0, 1/3]` or `[-1/3, 0]`), so it is bounded by its value at the appropriate endpoint; these values
are bounded by the rational certificates for `log` of `Numerics.lean`, and the sum of the fourteen
bounds is `≤ -18/25` (true maximum of `Φ(·, 0)`: `-0.80049` at `ξ ≈ 0.02503`).
-/

set_option linter.style.longLine false

open Real

noncomputable section

namespace Zeta2.Pair.Landscape

/-- The real profile `Φ(ξ, 0)` of configuration E (`η = (-17, 1, 2, 3, 5, 6)/40`). -/
def Preal (ξ : ℝ) : ℝ :=
  (xlx (ξ + 23 / 40) - xlx (ξ + 17 / 40)) + (xlx (ξ + 41 / 40) - xlx (ξ - 1 / 40)) +
    (xlx (ξ + 21 / 20) - xlx (ξ - 1 / 20)) + (xlx (ξ + 43 / 40) - xlx (ξ - 3 / 40)) +
    (xlx (ξ + 9 / 8) - xlx (ξ - 1 / 8)) + (xlx (ξ + 23 / 20) - xlx (ξ - 3 / 20)) -
    6 * (xlx (ξ + 1) - xlx ξ)
'''


def generate(cells=CELLS):
    facts = {}; fact_lines = []

    def xlx_fact(v, dirn):
        key = (v, dirn)
        if key in facts: return facts[key]
        name = "rx%d" % (len(facts) + 1)
        c, t = xlx_bound(v, dirn)
        if v == 0:
            stmt = "xlx 0 ≤ 0" if dirn == 'up' else "0 ≤ xlx 0"
            fact_lines.append("theorem %s : %s := by simp [xlx]\n" % (name, stmt))
        else:
            stmt = ("xlx %s ≤ %s" % (rnum(v), rnum(c))) if dirn == 'up' else ("%s ≤ xlx %s" % (rnum(c), rnum(v)))
            pre = "unfold xlx" if v > 0 else "rw [xlx_neg]; unfold xlx"
            fact_lines.append("theorem %s : %s := by\n  have h := %s\n  %s; linarith\n" % (name, stmt, t, pre))
        facts[key] = (name, c)
        return facts[key]

    cell_lines = []; report = []
    for ci, (l, r) in enumerate(cells, 1):
        L = Fr(l, D); R = Fr(r, D); ms = []; ns = []; tot = Fr(0)
        for idx in ORDER:
            s, A = TERMS[idx]
            k = kind(L + A, R + A); sd = side(s, k)
            v = (R if sd == 'r' else L) + A; x = arg_expr(A)
            if k == 'inc':
                if sd == 'r':
                    ms.append("have : xlx (%s) ≤ xlx %s := xlx_mono (by linarith) (by linarith)" % (x, rnum(v)))
                else:
                    ms.append("have : xlx %s ≤ xlx (%s) := xlx_mono (by norm_num) (by linarith)" % (rnum(v), x))
            elif k == 'decp':
                if sd == 'r':
                    ms.append("have : xlx %s ≤ xlx (%s) := xlx_anti_pos (by linarith) (by linarith) (by norm_num)" % (rnum(v), x))
                else:
                    ms.append("have : xlx (%s) ≤ xlx %s := xlx_anti_pos (by norm_num) (by linarith) (by linarith)" % (x, rnum(v)))
            else:
                assert sd == 'r'
                ms.append("have : xlx %s ≤ xlx (%s) := xlx_anti_neg (by linarith) (by linarith) (by norm_num)" % (rnum(v), x))
            name, c = xlx_fact(v, 'up' if s > 0 else 'lo')
            ns.append(name); tot += s*c
        assert tot <= TARGET, (l, r, float(tot))
        report.append((l, r, float(tot)))
        cell_lines.append("/-- Cell `[%s, %s]` (certified bound `%.6f`). -/" % (num(L), num(R), float(tot)))
        cell_lines.append("theorem real_cell_%d (ξ : ℝ) (h1 : %s ≤ ξ) (h2 : ξ ≤ %s) : Preal ξ ≤ -18 / 25 := by"
                          % (ci, rnum(L), rnum(R)))
        cell_lines += ["  " + m for m in ms]
        cell_lines.append("  unfold Preal")
        cell_lines.append("  linarith [%s]" % ", ".join(ns))
        cell_lines.append("")
    fin = ["/-- **(L-ii)** `Φ(ξ, 0) ≤ -18/25` on `[1/40, 7/100]`. -/",
           "theorem Preal_le : ∀ ξ ∈ Set.Icc (1 / 40 : ℝ) (7 / 100), Preal ξ ≤ -18 / 25 := by",
           "  rintro ξ ⟨h1, h2⟩"]
    for ci, (l, r) in enumerate(cells, 1):
        if ci < len(cells):
            fin.append("  rcases le_or_gt ξ %s with c%d | c%d" % (rnum(Fr(r, D)), ci, ci))
            fin.append("  · exact real_cell_%d ξ (by linarith) c%d" % (ci, ci))
        else:
            fin.append("  exact real_cell_%d ξ (by linarith) h2" % ci)
    fin.append("")
    out = (HEADER + "\n/-! ## Certified values of `x log x` at the grid points -/\n\n" + "\n".join(fact_lines)
           + "\n/-! ## The cells -/\n\n" + "\n".join(cell_lines) + "\n".join(fin) + "\nend Zeta2.Pair.Landscape\n")
    return out, report, len(facts)


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "search":
        print(search()); sys.exit(0)
    out, report, nf = generate()
    here = os.path.dirname(os.path.abspath(__file__))
    dest = sys.argv[1] if len(sys.argv) > 1 else os.path.join(here, "..", "RealProfile.lean")
    with open(dest, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(out)
    print(nf, "facts;", report)
